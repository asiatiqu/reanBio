def update_content(apps, schema_editor):
    Lesson = apps.get_model("reanBio", "Lesson")
    Checkpoint = apps.get_model("reanBio", "Checkpoint")
    CheckpointChoice = apps.get_model("reanBio", "CheckpointChoice")

    mapping = [
        ("1.1", PARAS_1_1, CHECKPOINTS_1_1),
        ("1.2", PARAS_1_2, CHECKPOINTS_1_2),
        ("1.3", PARAS_1_3, CHECKPOINTS_1_3),
    ]

    for prefix, paras, checkpoints in mapping:
        lesson = Lesson.objects.filter(grade="m4", title__startswith=prefix).first()
        if not lesson:
            continue

        lesson.content = "\n\n".join(paras)
        lesson.save(update_fields=["content"])

        # ล้าง checkpoint เดิมของบทเรียนนี้ก่อน (เผื่อรัน migration ซ้ำ) แล้วสร้างใหม่ตามตำแหน่งที่เลื่อนไป
        Checkpoint.objects.filter(lesson=lesson).delete()
        for order, (after_paragraph, text, choices, explanation) in enumerate(checkpoints, start=1):
            cp = Checkpoint.objects.create(
                lesson=lesson, after_paragraph=after_paragraph, order=order,
                text=text, explanation=explanation,
            )
            for c_order, (choice_text, is_correct) in enumerate(choices, start=1):
                CheckpointChoice.objects.create(
                    checkpoint=cp, order=c_order, text=choice_text, is_correct=is_correct,
                )


